"""Алгоритмическое задание.

Выводит первые n элементов последовательности, где число k повторяется k раз:
1 2 2 3 3 3 4 4 4 4 ... — слитно, без разделителей.
"""

n = int(input("Введите n: "))

result = []
num = 1
# Пока не набрали нужное количество элементов, дописываем очередное число num
# ровно num раз. Итоговая длина может превысить n — лишнее отсекается срезом ниже.
while len(result) < n:
    result.extend([num] * num)
    num += 1

print(*result[:n], sep="")
